"""
Container Architect Agent for Forward Deployment Engineers.
Generates production-grade, hardened Dockerfiles and .dockerignore files.
"""

import os
from typing import Dict

from fde_agent.llm import LLMFactory
from fde_agent.state import FDEAgentState
from fde_agent.tools.code_validator import clean_code_fences, write_file_safe


DOCKERIGNORE_CONTENT = """# Git & VCS
.git
.gitignore
.github

# Python caches
__pycache__/
*.py[cod]
*$py.class
*.so
.pytest_cache/
.mypy_cache/
.ruff_cache/

# Virtual Environments
venv/
.venv/
env/

# Environment and Secrets
.env
*.env
*.key
*.pem

# Backups and temporary files
*.bak
*.tmp
.DS_Store
Thumbs.db
"""


DOCKER_SYSTEM_PROMPT = """
You are a Principal Container Architect and Forward Deployment Engineer.
Your task is to write a hardened, production-ready Dockerfile for an enterprise Python application.

ENTERPRISE SPECIFICATIONS:
1. Use `python:3.11-slim` or `python:3.12-slim` as the base image.
2. Optimize caching: Copy `requirements.txt` first and run `pip install --no-cache-dir -r requirements.txt`.
3. Security Hardening: MUST create and switch to an unprivileged non-root user (e.g. `RUN useradd -m -u 10001 appuser`, `USER appuser`).
4. Set `WORKDIR /app` and `ENV PYTHONUNBUFFERED=1 PYTHONDONTWRITEBYTECODE=1`.
5. Include a HEALTHCHECK command if a web service or long-running entrypoint is detected.
6. Return ONLY the Dockerfile contents. Do not include markdown fences or trailing explanations.
"""


def container_architect_node(state: FDEAgentState) -> Dict:
    """
    LangGraph Node: Container Architect Agent.
    Generates hardened Dockerfile and .dockerignore.
    """
    project_path = state["project_path"]
    profile = state.get("profile")
    proj_type = profile.project_type if profile else "Python Application"
    entrypoint = profile.entrypoint if profile else "main.py"

    prompt = f"""
Project Type: {proj_type}
Detected Entrypoint: {entrypoint}

Generate a hardened, production-ready Dockerfile for this repository following all enterprise security best practices.
"""

    raw_response = LLMFactory.invoke_with_fallback(
        prompt=prompt,
        system_instruction=DOCKER_SYSTEM_PROMPT,
        max_tokens=2048,
    )

    dockerfile_content = clean_code_fences(raw_response, "dockerfile")

    # Fallback to deterministic template if response is malformed
    if "FROM " not in dockerfile_content:
        dockerfile_content = f"""# Production Hardened Dockerfile - Generated by FDE Multi-Agent System
FROM python:3.11-slim

# Prevent Python from buffering stdout/stderr and writing pyc files
ENV PYTHONUNBUFFERED=1 \\
    PYTHONDONTWRITEBYTECODE=1 \\
    PIP_NO_CACHE_DIR=1

WORKDIR /app

# Install system dependencies if required
RUN apt-get update && apt-get install -y --no-install-recommends \\
    curl \\
    && rm -rf /var/lib/apt/lists/*

# Layer caching for Python dependencies
COPY requirements.txt /app/
RUN pip install --no-cache-dir -r requirements.txt

# Create unprivileged non-root user
RUN useradd -m -u 10001 appuser && \\
    chown -R appuser:appuser /app

# Copy application files
COPY --chown=appuser:appuser . /app/

# Switch to unprivileged execution
USER appuser

EXPOSE 8000

CMD ["python", "{entrypoint or 'main.py'}"]
"""

    dockerfile_path = os.path.join(project_path, "Dockerfile")
    write_file_safe(dockerfile_path, dockerfile_content, make_backup=True)

    # Write .dockerignore
    dockerignore_path = os.path.join(project_path, ".dockerignore")
    write_file_safe(dockerignore_path, DOCKERIGNORE_CONTENT, make_backup=False)

    return {
        "dockerfile_path": dockerfile_path,
        "dockerfile_content": dockerfile_content,
        "status": "CONTAINER_SPEC_GENERATED",
    }

